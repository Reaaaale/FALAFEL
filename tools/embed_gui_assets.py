#!/usr/bin/env python3
"""Embed the small Falafel OS PNG illustrations as LVGL image descriptors."""

from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
ASSETS = (
    ("falafel_asset_taxi", ROOT / "shared/assets/falafel_taxi.png"),
    ("falafel_asset_cook", ROOT / "shared/assets/falafel_cook.png"),
    ("falafel_asset_reminder", ROOT / "shared/assets/falafel_reminder.png"),
)
OUTPUT = ROOT / "shared/gui/falafel_assets.c"


def png_size(data: bytes) -> tuple[int, int]:
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("asset is not a PNG")
    return struct.unpack(">II", data[16:24])


lines = [
    "/* Generated by tools/embed_gui_assets.py. */",
    '#include "falafel_gui_internal.h"',
    "",
]
for symbol, path in ASSETS:
    data = path.read_bytes()
    width, height = png_size(data)
    lines.append(f"static const uint8_t {symbol}_map[] = {{")
    for offset in range(0, len(data), 16):
        chunk = data[offset:offset + 16]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.extend((
        "};",
        f"const lv_image_dsc_t {symbol} = {{",
        "    .header.magic = LV_IMAGE_HEADER_MAGIC,",
        "    .header.cf = LV_COLOR_FORMAT_RAW_ALPHA,",
        f"    .header.w = {width},",
        f"    .header.h = {height},",
        f"    .data_size = sizeof({symbol}_map),",
        f"    .data = {symbol}_map,",
        "};",
        "",
    ))

OUTPUT.write_text("\n".join(lines), encoding="utf-8")
